import { chromium } from 'playwright'
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: 'th-TH', timezoneId: 'Asia/Bangkok' })
const p = await ctx.newPage()
p.on('console', (m) => m.type() === 'error' && console.log('console:', m.text()))
p.on('pageerror', (e) => console.log('pageerror:', e.message))
await p.goto('http://localhost:4174/chip-dept/')
await p.waitForTimeout(800)
await p.screenshot({ path: '/tmp/q-home0.png', fullPage: true })
await p.click('[data-testid=import-seed]')
await p.waitForTimeout(1200)
await p.screenshot({ path: '/tmp/q-home1.png', fullPage: true })
await p.goto('http://localhost:4174/chip-dept/#/entry?d=2026-11-16&s=yuka')
await p.waitForTimeout(600)
await p.screenshot({ path: '/tmp/q-entry.png', fullPage: true })
await p.goto('http://localhost:4174/chip-dept/#/report')
await p.waitForTimeout(600)
await p.screenshot({ path: '/tmp/q-report.png', fullPage: true })
await b.close()
